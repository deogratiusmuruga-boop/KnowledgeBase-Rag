# MISSING VALUES
# =====================================================================

def validate_missing_values(
    rows: list[dict[str, Any]],
    malformed_rows: list[int],
) -> bool:

    print()
    print("=" * 70)
    print("6. CSV MISSING VALUE ANALYSIS")
    print("=" * 70)

    if not rows:

        print(
            "[FAIL] CSV contains no data rows."
        )

        return False

    if malformed_rows:

        print(
            "[WARN] CSV rows are malformed."
        )

        print(
            "       Missing-value analysis is limited "
            "because DictReader cannot reliably map "
            "shifted fields."
        )

    failed = False

    columns = [
        column
        for column in rows[0].keys()
        if column is not None
    ]

    for column in columns:

        missing = sum(
            1
            for row in rows
            if not clean_string(
                row.get(column)
            )
        )

        percentage = (
            missing / len(rows) * 100
        )

        print(
            f"{str(column):<40}: "
            f"{missing:>8,} "
            f"({percentage:>6.2f}%)"
        )

    required_columns = [
        "patient_id",
        "first_event_date",
        "last_event_date",
        "timeline_days",
        "total_event_count",
    ]

    for column in required_columns:

        missing = sum(
            1
            for row in rows
            if not clean_string(
                row.get(column)
            )
        )

        if missing > 0:

            print(
                f"[FAIL] {column} has "
                f"{missing:,} missing values."
            )

            failed = True

    if not failed:

        print()
        print(
            "[PASS] Required clinical feature "
            "fields are populated."
        )

    return not failed


# =====================================================================
# NUMERIC VALIDATION
# =====================================================================

def validate_numeric_features(
    rows: list[dict[str, Any]],
    malformed_rows: list[int],
) -> bool:

    print()
    print("=" * 70)
    print("7. NUMERIC FEATURE VALIDATION")
    print("=" * 70)

    if malformed_rows:

        print(
            "[SKIP] Numeric CSV validation skipped."
        )

        print(
            "       Reason: CSV row alignment is corrupted."
        )

        print(
            "       Running numeric validation here would "
            "produce false failures."
        )

        return False

    failed = False

    for column in NUMERIC_COLUMNS:

        invalid = 0
        bad_values = 0
        negative = 0

        for row in rows:

            value = row.get(column)

            if not clean_string(value):
                continue

            if is_bad_numeric(value):

                bad_values += 1
                continue

            number = safe_float(value)

            if number is None:

                invalid += 1
                continue

            if (
                column in COUNT_COLUMNS
                and number < 0
            ):

                negative += 1

        if invalid:

            print(
                f"[FAIL] {column}: "
                f"{invalid:,} invalid numeric values."
            )

            failed = True

        if bad_values:

            print(
                f"[FAIL] {column}: "
                f"{bad_values:,} NaN/Infinity values."
            )

            failed = True

        if negative:

            print(
                f"[FAIL] {column}: "
                f"{negative:,} negative count values."
            )

            failed = True

    if not failed:

        print(
            "[PASS] Numeric clinical features are valid."
        )

    return not failed


