def validate_against_source_profiles(
    feature_rows: list[dict[str, Any]],
    source_profiles: list[dict[str, Any]],
) -> bool:

    print()
    print("=" * 70)
    print("14. CROSS-CHECK AGAINST PATIENT PROFILES")
    print("=" * 70)

    source_by_id = {
        clean_string(
            profile.get("patient_id")
        ): profile
        for profile in source_profiles
        if clean_string(
            profile.get("patient_id")
        )
    }

    failed = False

    comparisons = [
        (
            "total_event_count",
            lambda p: get_total_source_events(p),
        ),
        (
            "medication_event_count",
            lambda p: get_numeric_source_value(
                p,
                "medication_event_count",
            ),
        ),
        (
            "observation_event_count",
            lambda p: get_numeric_source_value(
                p,
                "observation_count",
            ),
        ),
        (
            "encounter_event_count",
            lambda p: get_numeric_source_value(
                p,
                "encounter_count",
            ),
        ),
        (
            "procedure_event_count",
            lambda p: get_numeric_source_value(
                p,
                "procedure_count",
            ),
        ),
        (
            "diagnostic_report_event_count",
            lambda p: get_numeric_source_value(
                p,
                "diagnostic_report_count",
            ),
        ),
        (
            "immunization_event_count",
            lambda p: get_numeric_source_value(
                p,
                "immunization_count",
            ),
        ),
    ]

    for feature_column, source_function in comparisons:

        mismatches = 0
        missing_sources = 0
        compared = 0

        for row in feature_rows:

            patient_id = clean_string(
                row.get("patient_id")
            )

            source = source_by_id.get(
                patient_id
            )

            if source is None:

                missing_sources += 1
                continue

            feature_value = safe_int(
                row.get(feature_column)
            )

            source_value = source_function(
                source
            )

            if (
                feature_value is None
                or source_value is None
            ):
                continue

            compared += 1

            if feature_value != source_value:

                mismatches += 1

                if mismatches <= 5:

                    print(
                        f"[DETAIL] {feature_column} "
                        f"mismatch for {patient_id}: "
                        f"features={feature_value}, "
                        f"source={source_value}"
                    )

        print(
            f"{feature_column:<35}: "
            f"{mismatches:,} mismatches "
            f"({compared:,} compared)"
        )

        if missing_sources:

            print(
                f"{feature_column:<35}: "
                f"{missing_sources:,} source profiles missing"
            )

            failed = True

        if mismatches:

            failed = True

    if not failed:

        print(
            "[PASS] Clinical feature counts "
            "agree with source profiles."
        )

    else:

        print(
            "[FAIL] Some clinical feature counts "
            "disagree with source profiles."
        )

    return not failed


