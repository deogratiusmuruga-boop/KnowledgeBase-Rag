def load_json_list(
    path: Path,
) -> list[dict[str, Any]]:

    with path.open(
        "r",
        encoding="utf-8",
    ) as file:

        data = json.load(file)

    if not isinstance(data, list):

        raise ValueError(
            f"{path.name} must contain a JSON list."
        )

    return [
        item
        for item in data
        if isinstance(item, dict)
    ]


