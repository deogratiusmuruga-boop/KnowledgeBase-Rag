    print()

    if malformed_rows:

        print(
            "[WARN] Global feature totals are affected "
            "by malformed CSV serialization."
        )

    if not failed:

        print(
            "[PASS] Global clinical event totals "
            "match the source profiles."
        )

    return not failed


