def validate_recent_activity(
    rows: list[dict[str, Any]],
    malformed_rows: list[int],
) -> bool:

    print()
    print("=" * 70)
    print("16. RECENT 365-DAY ACTIVITY")
    print("=" * 70)

    if malformed_rows:

        print(
            "[SKIP] Recent CSV activity validation "
            "because CSV rows are malformed."
        )

        return False

    failed = False

    for row in rows:

        patient_id = clean_string(
            row.get("patient_id")
        )

        recent_total = safe_float(
            row.get(
                "recent_event_count_365d"
            )
        )

        recent_medications = safe_float(
            row.get(
                "recent_medication_event_count_365d"
            )
        )

        recent_observations = safe_float(
            row.get(
                "recent_observation_event_count_365d"
            )
        )

        recent_conditions = safe_float(
            row.get(
                "recent_condition_event_count_365d"
            )
        )

        recent_encounters = safe_float(
            row.get(
                "recent_encounter_count_365d"
            )
        )

        sub_total = sum(
            value
            for value in [
                recent_medications,
                recent_observations,
                recent_conditions,
                recent_encounters,
            ]
            if value is not None
        )

        if (
            recent_total is not None
            and recent_total < 0
        ):

            print(
                f"[FAIL] Negative recent activity: "
                f"{patient_id}"
            )

            failed = True

        if (
            recent_total is not None
            and sub_total > recent_total
        ):

            print(
                f"[FAIL] Recent sub-category counts "
                f"exceed recent total: "
                f"{patient_id}"
            )

            failed = True

    total_recent = sum(
        safe_int(
            row.get(
                "recent_event_count_365d"
            )
        ) or 0
        for row in rows
    )

    print(
        f"Total recent 365-day events: "
        f"{total_recent:,}"
    )

    if not failed:

        print(
            "[PASS] Recent activity features are valid."
        )

    return not failed


