# JSON FEATURE CONTENT
# =====================================================================

def validate_feature_content(
    profiles: list[dict[str, Any]],
) -> bool:

    print()
    print("=" * 70)
    print("12. JSON CLINICAL FEATURE CONTENT")
    print("=" * 70)

    feature_groups = {
        "conditions": 0,
        "allergies": 0,
        "medications": 0,
        "observations": 0,
    }

    malformed_fields = 0

    for profile in profiles:

        for field in feature_groups:

            value = profile.get(field)

            if value is None:
                continue

            if not isinstance(
                value,
                list,
            ):

                malformed_fields += 1

                print(
                    f"[FAIL] {field} is not a list "
                    f"for patient "
                    f"{profile.get('patient_id')}"
                )

                continue

            if value:
                feature_groups[field] += 1

    for field, count in feature_groups.items():

        print(
            f"Profiles with {field:<14}: "
            f"{count:,}"
        )

    timeline_count = 0
    total_events = 0

    for profile in profiles:

        events = profile.get(
            "timeline_events"
        )

        if events is None:
            continue

        if not isinstance(
            events,
            list,
        ):

            malformed_fields += 1

            print(
                f"[FAIL] timeline_events is not "
                f"a list for patient "
                f"{profile.get('patient_id')}"
            )

            continue

        if events:
            timeline_count += 1

        total_events += len(events)

    print()

    print(
        "Profiles containing "
        f"timeline_events: {timeline_count:,}"
    )

    print(
        "Timeline events represented: "
        f"{total_events:,}"
    )

    if not malformed_fields:

        print(
            "[PASS] JSON clinical feature "
            "structures are valid."
        )

    else:

        print(
            "[FAIL] JSON feature structures "
            "contain malformed fields."
        )

    return malformed_fields == 0


