def load_csv() -> tuple[
    list[dict[str, Any]],
    list[str],
    list[int],
]:

    print()
    print("=" * 70)
    print("2. CSV VALIDATION")
    print("=" * 70)

    with CLINICAL_FEATURES_CSV.open(
        "r",
        encoding="utf-8",
        newline="",
    ) as file:

        reader = csv.DictReader(file)

        rows = list(reader)

        columns = reader.fieldnames or []

    malformed_rows = [
        index + 2
        for index, row in enumerate(rows)
        if None in row
    ]

    print(f"Rows:       {len(rows):,}")
    print(f"Columns:    {len(columns):,}")

    print()
    print("CSV columns:")

    for column in columns:
        print(f"  - {column}")

    print()

    if malformed_rows:

        print(
            "[FAIL] CSV serialization problem detected."
        )

        print(
            f"       {len(malformed_rows):,} rows contain "
            "extra fields beyond the header."
        )

        print(
            "       This usually means comma-containing "
            "fields were not CSV-quoted."
        )

        print(
            "       Numeric validation of these rows will "
            "be skipped to avoid false failures."
        )

    else:

        print(
            "[PASS] CSV rows are structurally aligned "
            "with the header."
        )

    return rows, columns, malformed_rows


