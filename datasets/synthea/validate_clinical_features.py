    print("=" * 70)

    if malformed_rows:

        print(
            "[SKIP] CSV range validation skipped "
            "because CSV rows are malformed."
        )

        return False

    failed = False

    for row in rows:

        patient_id = clean_string(
            row.get("patient_id")
        )

        timeline_days = safe_float(
            row.get("timeline_days")
        )

        total_events = safe_float(
            row.get("total_event_count")
        )

        dated_events = safe_float(
            row.get("dated_event_count")
        )

        undated_events = safe_float(
            row.get("undated_event_count")
        )

        if (
            timeline_days is not None
            and timeline_days < 0
        ):

            print(
                f"[FAIL] Negative timeline_days: "
                f"{patient_id}"
            )

            failed = True

        if (
            total_events is not None
            and dated_events is not None
            and undated_events is not None
        ):

            calculated = (
                dated_events
                + undated_events
            )

            if calculated != total_events:

                print(
                    f"[FAIL] Event count mismatch: "
                    f"{patient_id} "
                    f"(dated={dated_events}, "
                    f"undated={undated_events}, "
                    f"total={total_events})"
                )

                failed = True

        minimum = safe_float(
            row.get(
                "numeric_observation_min"
            )
        )

        maximum = safe_float(
            row.get(
                "numeric_observation_max"
            )
        )

        if (
            minimum is not None
            and maximum is not None
            and minimum > maximum
        ):

            print(
                f"[FAIL] Observation min > max: "
                f"{patient_id}"
            )

            failed = True

    if not failed:

        print(
            "[PASS] Feature ranges and "
            "event arithmetic are valid."
        )

    return not failed


