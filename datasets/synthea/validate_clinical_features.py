def clean_string(value: Any) -> str:
    if value is None:
        return ""

    return str(value).strip()


def safe_float(value: Any) -> float | None:
    if value is None:
        return None

    text = clean_string(value)

    if not text:
        return None

    try:
        result = float(text)

        if math.isnan(result) or math.isinf(result):
            return None

        return result

    except (TypeError, ValueError):
        return None


def safe_int(value: Any) -> int | None:
    number = safe_float(value)

    if number is None:
        return None

    if not number.is_integer():
        return None

    return int(number)


def is_bad_numeric(value: Any) -> bool:

    if value is None:
        return False

    if isinstance(value, str):

        text = value.strip().lower()

        return text in {
            "nan",
            "+nan",
            "-nan",
            "inf",
            "+inf",
            "-inf",
            "infinity",
            "+infinity",
            "-infinity",
        }

    if isinstance(value, float):

        return (
            math.isnan(value)
            or math.isinf(value)
        )

    return False


def parse_json_field(value: Any) -> Any:

    if value is None:
        return None

    text = clean_string(value)

    if not text:
        return None

    try:
        return json.loads(text)

    except json.JSONDecodeError:
        return None


def get_numeric_source_value(
    profile: dict[str, Any],
    key: str,
) -> int | None:

    value = profile.get(key)

    if isinstance(value, list):
        return len(value)

    return safe_int(value)


def get_total_source_events(
    profile: dict[str, Any],
) -> int:

    timeline = profile.get("timeline_events")

    if isinstance(timeline, list):
        return len(timeline)

    total = 0

    for source_key in SOURCE_COUNT_MAPPING.values():

        value = get_numeric_source_value(
            profile,
            source_key,
        )

        if value is not None:
            total += value

    return total


